//! Conversion and verification helpers at the manager/backend boundary.
//!
//! The manager owns the northbound idempotency and audit context.  This module
//! deliberately accepts only the small, already-canonical set of values needed
//! to build a backend `WriteContext`; backend-specific arguments stay in the
//! caller's typed method implementation.

use crate::v1;

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct ManagerActor {
    pub actor_id: String,
    pub actor_kind: i32,
    pub display_name: Option<String>,
    pub agent_session_id: Option<String>,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct DownstreamContextInput {
    pub method_key: String,
    pub canonical_target: String,
    pub schema_fingerprint: String,
    pub downstream_operation_id: String,
    pub actor: ManagerActor,
    pub correlation_id: String,
    pub reason: String,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct DownstreamContextError(pub(crate) String);

impl std::fmt::Display for DownstreamContextError {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(&self.0)
    }
}

impl std::error::Error for DownstreamContextError {}

/// Converts the manager-owned context into the backend's write context.
///
/// The operation ID is generated by the manager and is therefore validated as
/// a required value here.  No caller-provided backend context is accepted by
/// this conversion boundary.
pub(crate) fn build_downstream_context(
    input: &DownstreamContextInput,
) -> Result<v1::WriteContext, DownstreamContextError> {
    require_non_empty("method key", &input.method_key)?;
    require_non_empty("canonical target", &input.canonical_target)?;
    require_non_empty("schema fingerprint", &input.schema_fingerprint)?;
    require_non_empty("downstream operation ID", &input.downstream_operation_id)?;
    require_non_empty("actor ID", &input.actor.actor_id)?;
    require_non_empty("correlation ID", &input.correlation_id)?;
    if matches!(
        v1::ActorKind::try_from(input.actor.actor_kind),
        Ok(v1::ActorKind::Unspecified) | Err(_)
    ) {
        return Err(DownstreamContextError(
            "actor kind must be a known non-unspecified value".into(),
        ));
    }

    let caller = v1::ActorContext {
        actor: Some(v1::ActorRef {
            actor_id: input.actor.actor_id.clone(),
            kind: input.actor.actor_kind,
            display_name: input.actor.display_name.clone(),
        }),
        agent_session_id: input.actor.agent_session_id.clone(),
    };

    Ok(v1::WriteContext {
        request: Some(v1::RequestContext {
            caller: Some(caller),
            correlation_id: input.correlation_id.clone(),
        }),
        downstream_operation_id: input.downstream_operation_id.clone(),
        reason: input.reason.clone(),
    })
}

fn require_non_empty(name: &str, value: &str) -> Result<(), DownstreamContextError> {
    if value.trim().is_empty() {
        return Err(DownstreamContextError(format!("{name} must not be empty")));
    }
    Ok(())
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct EntityRevisionExpectation {
    pub issue_id: String,
    pub backend_id: String,
    pub resulting_revision: u64,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) struct MarkerExpectation {
    pub operation_id: String,
    pub method_key: String,
    pub scope: i32,
    pub payload_fingerprint: String,
    pub contract_fingerprint: String,
    pub affected_issue_ids: Vec<String>,
    pub entity_revisions: Vec<EntityRevisionExpectation>,
    /// A non-replayable claim has a durable marker but no result snapshot.
    pub result_replayable: bool,
}

#[derive(Debug, Clone, PartialEq, Eq)]
pub(crate) enum MarkerMismatch {
    MissingOperationId,
    OperationId,
    Method,
    Scope,
    PayloadFingerprint,
    ContractFingerprint,
    AffectedIssueIds,
    EntityRevisions,
    FingerprintInput,
    CommitDurability,
    ResultReplayability,
    ResultSnapshotMissing,
    ResultSnapshotUnexpected,
}

impl std::fmt::Display for MarkerMismatch {
    fn fmt(&self, formatter: &mut std::fmt::Formatter<'_>) -> std::fmt::Result {
        formatter.write_str(match self {
            Self::MissingOperationId => "operation marker has no operation ID",
            Self::OperationId => "operation ID does not match",
            Self::Method => "operation method does not match",
            Self::Scope => "operation scope does not match",
            Self::PayloadFingerprint => "operation payload fingerprint does not match",
            Self::ContractFingerprint => "operation contract fingerprint does not match",
            Self::AffectedIssueIds => "operation issue IDs do not match",
            Self::EntityRevisions => "operation entity revisions do not match",
            Self::FingerprintInput => "operation fingerprint input does not match",
            Self::CommitDurability => "operation is not durably committed",
            Self::ResultReplayability => "operation result replayability does not match",
            Self::ResultSnapshotMissing => "replayable operation has no result snapshot",
            Self::ResultSnapshotUnexpected => "non-replayable operation has a result snapshot",
        })
    }
}

/// Verifies every manager-owned field that identifies a backend commit.
///
/// A marker that merely contains the expected operation ID is insufficient:
/// method, scope, digest, target revisions, and durability must all agree
/// before the manager can publish a confirmed mutation.
pub(crate) fn verify_operation_marker(
    marker: &v1::OperationRecord,
    expected: &MarkerExpectation,
) -> Result<(), MarkerMismatch> {
    if marker.downstream_operation_id.is_empty() {
        return Err(MarkerMismatch::MissingOperationId);
    }
    if marker.downstream_operation_id != expected.operation_id {
        return Err(MarkerMismatch::OperationId);
    }
    if marker.method_key != expected.method_key {
        return Err(MarkerMismatch::Method);
    }
    if marker.scope != expected.scope {
        return Err(MarkerMismatch::Scope);
    }
    if marker.payload_fingerprint != expected.payload_fingerprint {
        return Err(MarkerMismatch::PayloadFingerprint);
    }
    if marker.contract_fingerprint != expected.contract_fingerprint {
        return Err(MarkerMismatch::ContractFingerprint);
    }

    let mut actual_issue_ids = marker.affected_issue_ids.clone();
    let mut expected_issue_ids = expected.affected_issue_ids.clone();
    actual_issue_ids.sort_unstable();
    expected_issue_ids.sort_unstable();
    if actual_issue_ids != expected_issue_ids {
        return Err(MarkerMismatch::AffectedIssueIds);
    }

    let mut actual_revisions = marker
        .entity_revisions
        .iter()
        .map(|revision| {
            (
                revision.issue_id.clone(),
                revision.backend_id.clone(),
                revision.resulting_revision,
            )
        })
        .collect::<Vec<_>>();
    let mut expected_revisions = expected
        .entity_revisions
        .iter()
        .map(|revision| {
            (
                revision.issue_id.clone(),
                revision.backend_id.clone(),
                revision.resulting_revision,
            )
        })
        .collect::<Vec<_>>();
    actual_revisions.sort_unstable();
    expected_revisions.sort_unstable();
    let revisions_match = if expected.method_key == "apply_issue_admin_action" {
        // RECOVER / REVOKE can legitimately record NO_CHANGE at the supplied
        // revision, while every changing administrative action advances it
        // once.  The expected record intentionally stores the input revision
        // so recovery after a restart can validate either immutable receipt
        // without reconstructing state from the current Issue.
        actual_revisions.len() == expected_revisions.len()
            && actual_revisions.iter().zip(&expected_revisions).all(
                |(
                    (actual_issue, actual_backend, actual_revision),
                    (expected_issue, expected_backend, expected_revision),
                )| {
                    actual_issue == expected_issue
                        && actual_backend == expected_backend
                        && (*actual_revision == *expected_revision
                            || expected_revision
                                .checked_add(1)
                                .is_some_and(|changed| *actual_revision == changed))
                },
            )
    } else {
        actual_revisions == expected_revisions
    };
    if !revisions_match {
        return Err(MarkerMismatch::EntityRevisions);
    }

    let input = marker
        .fingerprint_input
        .as_ref()
        .ok_or(MarkerMismatch::FingerprintInput)?;
    if input.downstream_operation_id != expected.operation_id
        || input.method_key != expected.method_key
        || input.scope != expected.scope
        || input.payload_fingerprint != expected.payload_fingerprint
    {
        return Err(MarkerMismatch::FingerprintInput);
    }

    if marker.commit_durability != v1::OperationCommitDurability::Durable as i32 {
        return Err(MarkerMismatch::CommitDurability);
    }
    match (
        expected.result_replayable,
        v1::OperationResultReplayability::try_from(marker.result_replayability),
    ) {
        (true, Ok(v1::OperationResultReplayability::Replayable)) => {
            if marker.result_snapshot.is_none() {
                return Err(MarkerMismatch::ResultSnapshotMissing);
            }
        }
        (false, Ok(v1::OperationResultReplayability::NotReplayable)) => {
            // Non-replayable operations may carry a redacted immutable
            // snapshot for audit/manual resolution.  The replayability bit,
            // rather than snapshot absence, prevents reissuing one-time
            // values such as a lease handle.
            if let Some(snapshot) = marker.result_snapshot.as_ref()
                && !matches!(
                    snapshot.value.as_ref(),
                    Some(v1::operation_result_snapshot::Value::IssueMutation(_))
                )
            {
                return Err(MarkerMismatch::ResultSnapshotUnexpected);
            }
        }
        _ => return Err(MarkerMismatch::ResultReplayability),
    }
    Ok(())
}

#[cfg(test)]
mod tests {
    use super::*;

    fn context_input() -> DownstreamContextInput {
        DownstreamContextInput {
            method_key: "manager_update_issue".into(),
            canonical_target: "lookback://issues/issue-1".into(),
            schema_fingerprint: "manager-schema".into(),
            downstream_operation_id: "downstream-1".into(),
            actor: ManagerActor {
                actor_id: "lookback:internal-llm-runner".into(),
                actor_kind: v1::ActorKind::InternalAgent as i32,
                display_name: Some("internal".into()),
                agent_session_id: Some("session-1".into()),
            },
            correlation_id: "correlation-1".into(),
            reason: "update requested".into(),
        }
    }

    #[test]
    fn converts_manager_context_without_accepting_backend_fields() {
        let context = build_downstream_context(&context_input()).expect("valid context");
        assert_eq!(context.downstream_operation_id, "downstream-1");
        assert_eq!(
            context.request.as_ref().expect("request").correlation_id,
            "correlation-1"
        );
        assert_eq!(
            context
                .request
                .as_ref()
                .and_then(|request| request.caller.as_ref())
                .and_then(|caller| caller.actor.as_ref())
                .map(|actor| actor.actor_id.as_str()),
            Some("lookback:internal-llm-runner")
        );
    }

    #[test]
    fn rejects_missing_server_owned_operation_id() {
        let mut input = context_input();
        input.downstream_operation_id.clear();
        assert!(build_downstream_context(&input).is_err());
    }

    fn marker() -> (v1::OperationRecord, MarkerExpectation) {
        let expected = MarkerExpectation {
            operation_id: "downstream-1".into(),
            method_key: "manager_update_issue".into(),
            scope: v1::OperationScope::Issue as i32,
            payload_fingerprint: "payload".into(),
            contract_fingerprint: "contract".into(),
            affected_issue_ids: vec!["issue-1".into()],
            entity_revisions: vec![EntityRevisionExpectation {
                issue_id: "issue-1".into(),
                backend_id: "backend-1".into(),
                resulting_revision: 4,
            }],
            result_replayable: true,
        };
        let marker = v1::OperationRecord {
            downstream_operation_id: expected.operation_id.clone(),
            affected_issue_ids: expected.affected_issue_ids.clone(),
            payload_fingerprint: expected.payload_fingerprint.clone(),
            contract_fingerprint: expected.contract_fingerprint.clone(),
            scope: expected.scope,
            method_key: expected.method_key.clone(),
            entity_revisions: vec![v1::OperationEntityRevision {
                issue_id: "issue-1".into(),
                backend_id: "backend-1".into(),
                resulting_revision: 4,
            }],
            commit_durability: v1::OperationCommitDurability::Durable as i32,
            result_replayability: v1::OperationResultReplayability::Replayable as i32,
            result_snapshot: Some(v1::OperationResultSnapshot::default()),
            fingerprint_input: Some(v1::OperationFingerprintInput {
                downstream_operation_id: expected.operation_id.clone(),
                method_key: expected.method_key.clone(),
                scope: expected.scope,
                payload_fingerprint: expected.payload_fingerprint.clone(),
            }),
            ..Default::default()
        };
        (marker, expected)
    }

    #[test]
    fn verifies_marker_identity_and_durability() {
        let (marker, expected) = marker();
        verify_operation_marker(&marker, &expected).expect("marker should verify");
    }

    #[test]
    fn rejects_marker_with_wrong_revision() {
        let (mut marker, expected) = marker();
        marker.entity_revisions[0].resulting_revision = 5;
        assert_eq!(
            verify_operation_marker(&marker, &expected),
            Err(MarkerMismatch::EntityRevisions)
        );
    }

    #[test]
    fn administrative_marker_accepts_only_no_change_or_one_atomic_revision() {
        let (mut marker, mut expected) = marker();
        expected.method_key = "apply_issue_admin_action".into();
        marker.method_key = expected.method_key.clone();
        marker.fingerprint_input.as_mut().unwrap().method_key = expected.method_key.clone();

        // The input revision is a valid NO_CHANGE receipt.
        verify_operation_marker(&marker, &expected).expect("NO_CHANGE should verify");

        marker.entity_revisions[0].resulting_revision = 5;
        verify_operation_marker(&marker, &expected)
            .expect("one atomic administrative mutation should verify");

        marker.entity_revisions[0].resulting_revision = 6;
        assert_eq!(
            verify_operation_marker(&marker, &expected),
            Err(MarkerMismatch::EntityRevisions)
        );
    }

    #[test]
    fn distinguishes_non_replayable_marker_from_unknown_replayability() {
        let (mut marker, mut expected) = marker();
        expected.result_replayable = false;
        marker.result_replayability = v1::OperationResultReplayability::NotReplayable as i32;
        marker.result_snapshot = None;
        verify_operation_marker(&marker, &expected).expect("durable claim marker");

        marker.result_replayability = v1::OperationResultReplayability::Unspecified as i32;
        assert_eq!(
            verify_operation_marker(&marker, &expected),
            Err(MarkerMismatch::ResultReplayability)
        );
    }
}
